-- ===================================================
-- KejaKU Database Schema for Supabase
-- Copy and run this script in Supabase SQL Editor
-- ===================================================

-- 1. ACCOUNTS TABLE
CREATE TABLE IF NOT EXISTS public.accounts (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  phone TEXT,
  role TEXT DEFAULT 'owner',
  house_ids JSONB DEFAULT '[]'::jsonb,
  avatar TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. HOUSES TABLE
CREATE TABLE IF NOT EXISTS public.houses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  area TEXT NOT NULL,
  landmark TEXT,
  type TEXT NOT NULL,
  floor TEXT,
  vacant_units INT DEFAULT 1,
  rent NUMERIC NOT NULL,
  deposit NUMERIC,
  garbage_fee NUMERIC DEFAULT 0,
  distance TEXT,
  water TEXT,
  electricity TEXT,
  wifi TEXT,
  gate_curfew TEXT,
  status TEXT DEFAULT 'visited',
  verified_date TEXT,
  caretaker TEXT,
  phone TEXT,
  whatsapp TEXT,
  image TEXT,
  images JSONB DEFAULT '[]'::jsonb,
  features JSONB DEFAULT '[]'::jsonb,
  rules JSONB DEFAULT '[]'::jsonb,
  description TEXT,
  owner_id TEXT REFERENCES public.accounts(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. ENQUIRIES TABLE
CREATE TABLE IF NOT EXISTS public.enquiries (
  id TEXT PRIMARY KEY,
  user_id TEXT REFERENCES public.accounts(id) ON DELETE SET NULL,
  house_id BIGINT,
  house_title TEXT,
  student_name TEXT NOT NULL,
  student_phone TEXT NOT NULL,
  viewing_date DATE,
  message TEXT,
  status TEXT DEFAULT 'open',
  messages JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. SAVED HOUSES TABLE (STUDENT BOOKMARKS)
CREATE TABLE IF NOT EXISTS public.saved_houses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES public.accounts(id) ON DELETE CASCADE,
  house_id BIGINT NOT NULL REFERENCES public.houses(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(user_id, house_id)
);

-- Optional: Performance Indexes
CREATE INDEX IF NOT EXISTS idx_houses_area ON public.houses(area);
CREATE INDEX IF NOT EXISTS idx_houses_rent ON public.houses(rent);
CREATE INDEX IF NOT EXISTS idx_houses_type ON public.houses(type);
CREATE INDEX IF NOT EXISTS idx_accounts_email ON public.accounts(email);
CREATE INDEX IF NOT EXISTS idx_enquiries_house ON public.enquiries(house_id);
